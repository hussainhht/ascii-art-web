import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { generateASCII, normalizeInput } from '../demo/js/ascii-generator.js';
import { BANNERS, parseFont, createFontLoader } from '../demo/js/font-loader.js';
import { makeTextBlob } from '../demo/js/download.js';
import { readStored, writeStored, readCount } from '../demo/js/storage.js';

const fonts = new Map();
for (const banner of BANNERS) fonts.set(banner, parseFont(await readFile(new URL(`../fonts/${banner}.txt`, import.meta.url), 'utf8'), banner));
const fixtures = JSON.parse(await readFile(new URL('./golden/outputs.json', import.meta.url), 'utf8'));
for (const [index, fixture] of fixtures.entries()) {
  test(`Go fixture ${index + 1}: ${fixture.banner} ${JSON.stringify(fixture.input)}`, () => {
    if (fixture.status === 200) assert.equal(generateASCII(fixture.input, fonts.get(fixture.banner)), fixture.output);
    else assert.throws(() => generateASCII(fixture.input, fonts.get(fixture.banner)), /printable ASCII/);
  });
}
test('input limit bounds generation work', () => {
  assert.throws(() => normalizeInput('a'.repeat(1001)), /at most 1000/);
  assert.ok(generateASCII('W'.repeat(1000), fonts.get('bigmoney')).length > 0);
});
test('font line endings normalize without trimming glyph spaces', async () => {
  for (const banner of BANNERS) {
    const text = await readFile(new URL(`../fonts/${banner}.txt`, import.meta.url), 'utf8');
    assert.deepEqual(parseFont(text.replace(/\r?\n/g, '\r\n'), banner), fonts.get(banner));
    assert.throws(() => parseFont('truncated', banner), /corrupted/);
    assert.throws(() => parseFont(text.replace(/[^\r\n]/, 'é'), banner), /invalid|corrupted/);
  }
  assert.throws(() => parseFont('', '../../backend'), /Choose/);
});
test('loader caches concurrent requests and retries failures', async () => {
  let requests = 0;
  const source = await readFile(new URL('../fonts/standard.txt', import.meta.url), 'utf8');
  const load = createFontLoader(async url => {
    requests++;
    assert.ok(url.pathname.endsWith('/fonts/standard.txt'));
    return { ok: requests > 1, text: async () => source };
  });
  await assert.rejects(load('standard'), /Could not load/);
  const [one, two] = await Promise.all([load('standard'), load('standard')]);
  assert.equal(one, two);
  assert.equal(requests, 2);
  await assert.rejects(load('invalid'), /Choose/);
});
test('TXT Blob contains exact generated bytes including trailing LF', async () => {
  for (const fixture of fixtures.filter(f => f.status === 200)) {
    assert.equal(await makeTextBlob(fixture.output).text(), fixture.output);
    assert.equal(makeTextBlob(fixture.output).size, Buffer.byteLength(fixture.output));
  }
});
test('blocked browser storage falls back to memory', () => {
  writeStored('count', 7);
  assert.equal(readCount(), 7);
  writeStored('count', -1);
  assert.equal(readCount(), 0);
  assert.equal(readStored('missing', 'fallback'), 'fallback');
});
